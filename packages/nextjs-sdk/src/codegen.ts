function renderCommandInputMap(commands: readonly FddpContractCommand[]): string {
  const sorted = [...commands].sort((a, b) => a.name.localeCompare(b.name));
  if (sorted.length === 0) {
    return "Record<never, never>";
  }
  const lines = sorted.map((command) => {
    return `  ${JSON.stringify(command.name)}: ${renderInputType(command.input ?? [])};`;
  });
  return ["{", ...lines, "}"].join("\n");
}

function renderInputType(fields: readonly FddpContractInputField[]): string {
  if (fields.length === 0) {
    return "Record<string, unknown>";
  }
  const lines = [...fields].sort((a, b) => a.field.localeCompare(b.field)).map((field) => {
    const optional = field.required ? "" : "?";
    return `  ${safePropertyName(field.field)}${optional}: ${inputTsType(field)};`;
  });
  return ["{", ...lines, "}"].join("\n");
}

