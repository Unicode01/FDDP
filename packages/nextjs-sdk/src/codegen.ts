function renderResourceQueryCallerNode(current: ResourceTreeNode, path: string[]): string {
  if (current.children.size === 0 && current.resource) {
    const resourceName = current.resource.path;
    const resourceType = JSON.stringify(resourceName);
    const queryObject = renderSingleResourceQueryObject(resourceName);
    return `(client: import("@fddp/next-sdk").FddpClient, query: FddpGeneratedCollectionQuery<${resourceType}> = {}, options?: import("@fddp/next-sdk").FddpQueryOptions) => client.query<FddpGeneratedResourceData<${resourceType}>>(${queryObject}, options)`;
  }

  const entries = Array.from(current.children.entries()).sort(([a], [b]) => a.localeCompare(b)).map(([key, child]) => {
    return `${JSON.stringify(key)}: ${renderResourceQueryCallerNode(child, [...path, key])}`;
  });
  return `{ ${entries.join(", ")} }`;
}

