function renderQueryCallers(resources: readonly FddpContractResource[]): string {
  return `{ query: (client: import("@fddp/next-sdk").FddpClient, query: import("@fddp/next-sdk").FddpQuery, options?: import("@fddp/next-sdk").FddpQueryOptions) => client.query<FddpGeneratedQueryData>(query, options), load: (client: import("@fddp/next-sdk").FddpClient, input: FddpGeneratedLoadQuery, options?: import("@fddp/next-sdk").FddpQueryOptions) => client.query<FddpGeneratedQueryData>(buildFddpGeneratedQuery(input), options), resource: ${renderResourceQueryCallers(resources)} }`;
}

function renderBoundFddpApi(
  resources: readonly FddpContractResource[],
  commands: readonly FddpContractCommand[]
): string {
  return `{ query: (query: import("@fddp/next-sdk").FddpQuery, options?: import("@fddp/next-sdk").FddpQueryOptions) => queryCallers.query(client, query, options), load: (input: FddpGeneratedLoadQuery, options?: import("@fddp/next-sdk").FddpQueryOptions) => queryCallers.load(client, input, options), resource: ${renderBoundResourceQueryCallers(resources)}, command: ${renderBoundCommandCallers(commands)} }`;
}

