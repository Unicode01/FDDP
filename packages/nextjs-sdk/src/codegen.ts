export function generateFddpTypes(schema: FddpContractSchema, options: FddpTypegenOptions = {}): string {
  validateFddpContractSchema(schema);
  const dataTypeName = options.dataTypeName ?? "FddpGeneratedData";
  const fieldsConstName = options.fieldsConstName ?? "fields";
  const resourcesConstName = options.resourcesConstName ?? "resources";
  const commandsConstName = options.commandsConstName ?? "commands";
  const root = buildTree(schema.fields);
  const resources = schema.resources ?? [];
  const commands = schema.commands ?? [];

  return [
    "/* eslint-disable */",
    "// This file is generated by FDDP. Do not edit by hand.",
    schema.protocolVersion ? `// protocolVersion: ${schema.protocolVersion}` : undefined,
    schema.contractVersion ? `// contractVersion: ${schema.contractVersion}` : undefined,
    "",
    `import { queryFromFields } from "@fddp/next-sdk";`,
    "",
    `export const ${fieldsConstName} = ${renderFieldConstants(root)} as const;`,
    "",
    `export const ${resourcesConstName} = ${renderPathConstants(resources.map((resource) => resource.path))} as const;`,
    "",
    `export const resourceCallers = ${renderResourceCallers(resources)} as const;`,
    "",
    `function buildFddpGeneratedQuery(input: FddpGeneratedLoadQuery): import("@fddp/next-sdk").FddpQuery {`,
    `  const query = (input.fields?.length ? queryFromFields(input.fields) : {}) as Record<string, any>;`,
    ...renderLoadQueryBuilderLines(resources),
    `  return query as import("@fddp/next-sdk").FddpQuery;`,
    `}`,
    "",
    `export const queryCallers = ${renderQueryCallers(resources)} as const;`,
    "",
    `export function createFddpApi(client: import("@fddp/next-sdk").FddpClient) {`,
    `  return ${renderBoundFddpApi(resources, commands)} as const;`,
    `}`,
    "",
    `export const ${commandsConstName} = ${renderPathConstants(commands.map((command) => command.name))} as const;`,
    "",
    `export const commandCallers = ${renderCommandCallers(commands)} as const;`,
    "",
    `export type ${dataTypeName} = ${renderType(root, 0)};`,
    "",
    `export type FddpGeneratedField = ${renderStringUnion(schema.fields.map((field) => field.field))};`,
    `export type FddpGeneratedResource = ${renderStringUnion(resources.map((resource) => resource.path))};`,
    `export type FddpGeneratedCommand = ${renderStringUnion(commands.map((command) => command.name))};`,
    `export type FddpGeneratedResourceItem<TResource extends FddpGeneratedResource> = FddpGeneratedResourceItemMap[TResource];`,
    `export type FddpGeneratedResourceResult<TResource extends FddpGeneratedResource> = FddpGeneratedCollectionResult<FddpGeneratedResourceItem<TResource>>;`,
    `export type FddpGeneratedResourceData<TResource extends FddpGeneratedResource> = FddpGeneratedResourceDataMap[TResource];`,
    `export type FddpGeneratedQueryData = ${dataTypeName} & FddpGeneratedAllResourceData;`,
    `export type FddpGeneratedLoadQuery = {`,
    `  fields?: readonly FddpGeneratedField[];`,
    ...renderLoadQueryResourceFields(resources),
    `};`,
    `export type FddpGeneratedResourceField<TResource extends FddpGeneratedResource> = FddpGeneratedResourceFieldMap[TResource];`,
    `export type FddpGeneratedResourceFilter<TResource extends FddpGeneratedResource> = Partial<Record<FddpGeneratedResourceField<TResource>, import("@fddp/next-sdk").FddpFilterValue>>;`,
    `export type FddpGeneratedResourceOrderBy<TResource extends FddpGeneratedResource> = { field: FddpGeneratedResourceField<TResource>; direction?: "asc" | "desc" };`,
    `export type FddpGeneratedResourceRelation<TResource extends FddpGeneratedResource> = keyof FddpGeneratedResourceRelationFieldMap[TResource] & string;`,
    `export type FddpGeneratedResourceRelationField<TResource extends FddpGeneratedResource, TRelation extends FddpGeneratedResourceRelation<TResource>> = FddpGeneratedResourceRelationFieldMap[TResource][TRelation];`,
    `export type FddpGeneratedResourceExpand<TResource extends FddpGeneratedResource> = {`,
    `  readonly [TRelation in FddpGeneratedResourceRelation<TResource>]?: readonly FddpGeneratedResourceRelationField<TResource, TRelation>[];`,
    `};`,
    `export type FddpGeneratedCollectionQuery<TResource extends FddpGeneratedResource> = Omit<import("@fddp/next-sdk").FddpCollectionArgs, "filter" | "orderBy"> & {`,
    `  fields?: readonly FddpGeneratedResourceField<TResource>[];`,
    `  filter?: FddpGeneratedResourceFilter<TResource>;`,
    `  orderBy?: readonly FddpGeneratedResourceOrderBy<TResource>[];`,
    `  expand?: FddpGeneratedResourceExpand<TResource>;`,
    `};`,
    `type FddpGeneratedResourceFieldMap = ${renderResourceFieldMap(resources)};`,
    `type FddpGeneratedResourceRelationFieldMap = ${renderResourceRelationFieldMap(resources)};`,
    `type FddpGeneratedResourceItemMap = ${renderResourceItemMap(resources)};`,
    `type FddpGeneratedResourceDataMap = ${renderResourceDataMap(resources)};`,
    `type FddpGeneratedAllResourceData = ${renderAllResourceDataType(resources)};`,
    `export type FddpGeneratedCommandInput<TCommand extends FddpGeneratedCommand> = ${renderCommandInputMap(commands)}[TCommand];`,
    "",
    `export type FddpGeneratedCollectionResult<TItem = unknown> = {`,
    `  items: TItem[];`,
    `  pageInfo?: { hasNextPage: boolean; hasPreviousPage?: boolean; startCursor?: string; endCursor?: string };`,
    `  totalCount?: number | null;`,
    `};`,
    ""
  ].filter((line): line is string => line !== undefined).join("\n");
}

export function validateFddpContractSchema(schema: FddpContractSchema): void {
  if (!schema || typeof schema !== "object" || !Array.isArray(schema.fields)) {
    throw new Error("Invalid FDDP contract: expected an object with a fields array.");
  }

  const seen = new Set<string>();
  for (const field of schema.fields) {
    if (!field || typeof field.field !== "string" || field.field.trim() === "") {
      throw new Error("Invalid FDDP contract: every field needs a non-empty field path.");
    }
    if (seen.has(field.field)) {
      throw new Error(`Invalid FDDP contract: duplicate field ${field.field}.`);
    }
    seen.add(field.field);
  }

  validateNamedPaths(schema.resources ?? [], "resource", (resource) => resource.path);
  validateNamedPaths(schema.commands ?? [], "command", (command) => command.name);

  for (const resource of schema.resources ?? []) {
    validateNamedPaths(resource.fields ?? [], `resource field for ${resource.path}`, (field) => field.field);
    validateNamedPaths(resource.relations ?? [], `resource relation for ${resource.path}`, (relation) => relation.name);
    for (const relation of resource.relations ?? []) {
      validateNamedPaths(relation.fields ?? [], `resource relation field for ${resource.path}.${relation.name}`, (field) => field.field);
    }
  }
}

export function diffFddpContracts(previous: FddpContractSchema, next: FddpContractSchema, options: FddpContractDiffOptions = {}): FddpContractDiff {
  validateFddpContractSchema(previous);
  validateFddpContractSchema(next);

  const breaking: FddpContractChange[] = [];
  const nonBreaking: FddpContractChange[] = [];
  const addBreaking = (path: string, message: string) => breaking.push({ severity: "breaking", path, message });
  const addNonBreaking = (path: string, message: string) => nonBreaking.push({ severity: "non-breaking", path, message });

  diffNamedItems(
    "field",
    byKey(previous.fields, (field) => field.field),
    byKey(next.fields, (field) => field.field),
    addBreaking,
    addNonBreaking,
    compareContractField
  );

  diffNamedItems(
    "resource",
    byKey(previous.resources ?? [], (resource) => resource.path),
    byKey(next.resources ?? [], (resource) => resource.path),
    addBreaking,
    addNonBreaking,
    (path, previousResource, nextResource, breaking, nonBreaking) => compareContractResource(path, previousResource, nextResource, options, breaking, nonBreaking)
  );

  diffNamedItems(
    "command",
    byKey(previous.commands ?? [], (command) => command.name),
    byKey(next.commands ?? [], (command) => command.name),
    addBreaking,
    addNonBreaking,
    (path, previousCommand, nextCommand, breaking, nonBreaking) => compareContractCommand(path, previousCommand, nextCommand, options, breaking, nonBreaking)
  );

  return { breaking, nonBreaking };
}

function buildTree(fields: readonly FddpContractField[]): TreeNode {
  const root = node();

  for (const field of fields) {
    const parts = field.field.split(".").filter(Boolean);
    if (parts.length === 0) {
      continue;
    }

    let current = root;
    for (const part of parts) {
      let next = current.children.get(part);
      if (!next) {
        next = node();
        current.children.set(part, next);
      }
      current = next;
    }
    current.field = field;
  }

  return root;
}

function node(): TreeNode {
  return { children: new Map() };
}

function resourceNode(): ResourceTreeNode {
  return { children: new Map() };
}

function renderFieldConstants(root: TreeNode): string {
  return renderConstNode(root, []);
}

function renderPathConstants(paths: readonly string[]): string {
  if (paths.length === 0) {
    return "{}";
  }
  const root = node();
  for (const path of paths) {
    const parts = path.split(".").filter(Boolean);
    if (parts.length === 0) {
      continue;
    }
    let current = root;
    for (const part of parts) {
      let next = current.children.get(part);
      if (!next) {
        next = node();
        current.children.set(part, next);
      }
      current = next;
    }
    current.field = { field: path, type: "string" };
  }
  return renderConstNode(root, []);
}

