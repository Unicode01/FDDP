function renderBoundCommandCallerNode(current: TreeNode, path: string[]): string {
  if (current.children.size === 0) {
    const commandName = path.join(".");
    const commandType = JSON.stringify(commandName);
    const access = path.map((part) => `[${JSON.stringify(part)}]`).join("");
    return `(input: FddpGeneratedCommandInput<${commandType}>, options?: import("@fddp/next-sdk").FddpCommandOptions) => commandCallers${access}(client, input, options)`;
  }

  const entries = sortedEntries(current.children).map(([key, child]) => {
    return `${JSON.stringify(key)}: ${renderBoundCommandCallerNode(child, [...path, key])}`;
  });
  return `{ ${entries.join(", ")} }`;
}

function renderSingleResourceQueryObject(resourcePath: string): string {
  const parts = resourcePath.split(".").filter(Boolean);
  if (parts.length === 0) {
    return "{}";
  }
  let out = "resourceCallers";
  for (const part of parts) {
    out += `[${JSON.stringify(part)}]`;
  }
  const descriptor = `${out}(query)`;
  let current = descriptor;
  for (let index = parts.length - 1; index >= 0; index--) {
    current = `{ ${JSON.stringify(parts[index])}: ${current} }`;
  }
  return current;
}

function renderLoadQueryResourceFields(resources: readonly FddpContractResource[]): string[] {
  return [...resources].sort((a, b) => a.path.localeCompare(b.path)).map((resource) => {
    return `  ${loadQueryKey(resource.path)}?: FddpGeneratedCollectionQuery<${JSON.stringify(resource.path)}>;`;
  });
}

function renderLoadQueryBuilderLines(resources: readonly FddpContractResource[]): string[] {
  return [...resources].sort((a, b) => a.path.localeCompare(b.path)).flatMap((resource) => {
    const key = loadQueryKey(resource.path);
    const parts = resource.path.split(".").filter(Boolean);
    if (parts.length === 0) {
      return [];
    }
    const lines = [`  if (input.${key}) {`];
    let current = "query";
    for (let index = 0; index < parts.length - 1; index++) {
      const part = JSON.stringify(parts[index]);
      lines.push(`    ${current}[${part}] ??= {};`);
      current = `${current}[${part}]`;
    }
    const leaf = JSON.stringify(parts[parts.length - 1]);
    lines.push(`    ${current}[${leaf}] = resourceCallers${parts.map((part) => `[${JSON.stringify(part)}]`).join("")}(input.${key});`);
    lines.push(`  }`);
    return lines;
  });
}

function loadQueryKey(path: string): string {
  const parts = path.split(".").filter(Boolean);
  if (parts.length === 0) {
    return "resource";
  }
  const [first, ...rest] = parts;
  return first + rest.map((part) => {
    const chars = Array.from(part);
    if (chars.length === 0) {
      return "";
    }
    return chars[0]!.toUpperCase() + chars.slice(1).join("");
  }).join("");
}

function renderResourceCallerNode(current: TreeNode, path: string[]): string {
  if (current.children.size === 0) {
    const resourceName = path.join(".");
    const resourceType = JSON.stringify(resourceName);
    return `(query: FddpGeneratedCollectionQuery<${resourceType}> = {}): import("@fddp/next-sdk").FddpCollectionDescriptor => ({ $type: "collection", args: { first: query.first, after: query.after, filter: query.filter, orderBy: query.orderBy }, selection: { fields: query.fields, expand: query.expand } })`;
  }

  const entries = sortedEntries(current.children).map(([key, child]) => {
    return `${JSON.stringify(key)}: ${renderResourceCallerNode(child, [...path, key])}`;
  });
  return `{ ${entries.join(", ")} }`;
}

