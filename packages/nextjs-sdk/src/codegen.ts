function sortedEntries(map: Map<string, TreeNode>): Array<[string, TreeNode]> {
  return Array.from(map.entries()).sort(([a], [b]) => a.localeCompare(b));
}

function safePropertyName(key: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
}

function renderStringUnion(values: readonly string[]): string {
  const unique = Array.from(new Set(values)).sort((a, b) => a.localeCompare(b));
  if (unique.length === 0) {
    return "never";
  }
  return unique.map((value) => JSON.stringify(value)).join(" | ");
}

function validateNamedPaths<T>(values: readonly T[], label: string, getPath: (value: T) => string): void {
  const seen = new Set<string>();
  for (const value of values) {
    const path = getPath(value);
    if (typeof path !== "string" || path.trim() === "") {
      throw new Error(`Invalid FDDP contract: every ${label} needs a non-empty path.`);
    }
    if (seen.has(path)) {
      throw new Error(`Invalid FDDP contract: duplicate ${label} ${path}.`);
    }
    seen.add(path);
  }
}

function byKey<T>(items: readonly T[], getKey: (item: T) => string): Map<string, T> {
  return new Map(items.map((item) => [getKey(item), item]));
}

function diffNamedItems<T>(
  label: string,
  previous: Map<string, T>,
  next: Map<string, T>,
  addBreaking: (path: string, message: string) => void,
  addNonBreaking: (path: string, message: string) => void,
  compare: (path: string, previous: T, next: T, addBreaking: (path: string, message: string) => void, addNonBreaking: (path: string, message: string) => void) => void
): void {
  for (const [path, previousItem] of previous) {
    const nextItem = next.get(path);
    if (!nextItem) {
      addBreaking(path, `${label} removed`);
      continue;
    }
    compare(path, previousItem, nextItem, addBreaking, addNonBreaking);
  }

  for (const path of next.keys()) {
    if (!previous.has(path)) {
      addNonBreaking(path, `${label} added`);
    }
  }
}

function compareContractField(
  path: string,
  previous: FddpContractField,
  next: FddpContractField,
  addBreaking: (path: string, message: string) => void,
  addNonBreaking: (path: string, message: string) => void
): void {
  compareTypeAndNullability(path, previous, next, addBreaking, addNonBreaking);
  compareDeprecated(path, previous.deprecated, next.deprecated, addNonBreaking);
  compareStringProperty(path, "permission", previous.permission, next.permission, addNonBreaking);
  compareStringProperty(path, "owner", previous.owner, next.owner, addNonBreaking);
  compareStringProperty(path, "cacheScope", previous.cacheScope, next.cacheScope, addNonBreaking);
}

function compareContractResource(
  path: string,
  previous: FddpContractResource,
  next: FddpContractResource,
  options: FddpContractDiffOptions,
  addBreaking: (path: string, message: string) => void,
  addNonBreaking: (path: string, message: string) => void
): void {
  compareDeprecated(path, previous.deprecated, next.deprecated, addNonBreaking);
  compareStringProperty(path, "permission", previous.permission, next.permission, addNonBreaking);
  compareStringProperty(path, "owner", previous.owner, next.owner, addNonBreaking);

  if ((previous.maxPageSize ?? 0) > 0 && (next.maxPageSize ?? previous.maxPageSize ?? 0) > 0 && (next.maxPageSize ?? 0) < (previous.maxPageSize ?? 0)) {
    addByPolicy(options.allowResourceMaxPageSizeDecrease, addBreaking, addNonBreaking, path, `resource maxPageSize decreased from ${previous.maxPageSize} to ${next.maxPageSize}`);
  } else if (previous.maxPageSize !== next.maxPageSize) {
    addNonBreaking(path, `resource maxPageSize changed from ${String(previous.maxPageSize)} to ${String(next.maxPageSize)}`);
  }

  const previousFields = byKey(previous.fields ?? [], (field) => field.field);
  const nextFields = byKey(next.fields ?? [], (field) => field.field);
  diffNamedItems(
    "resource field",
    previousFields,
    nextFields,
    (fieldPath, message) => addBreaking(`${path}.${fieldPath}`, message),
    (fieldPath, message) => addNonBreaking(`${path}.${fieldPath}`, message),
    (fieldPath, previousField, nextField, breaking, nonBreaking) => {
      const fullPath = `${path}.${fieldPath}`;
      compareResourceField(fullPath, previousField, nextField, breaking, nonBreaking);
    }
  );

  const previousRelations = byKey(previous.relations ?? [], (relation) => relation.name);
  const nextRelations = byKey(next.relations ?? [], (relation) => relation.name);
  diffNamedItems(
    "resource relation",
    previousRelations,
    nextRelations,
    (relationPath, message) => addBreaking(`${path}.${relationPath}`, message),
    (relationPath, message) => addNonBreaking(`${path}.${relationPath}`, message),
    (relationPath, previousRelation, nextRelation, breaking, nonBreaking) => {
      const previousRelationFields = byKey(previousRelation.fields ?? [], (field) => field.field);
      const nextRelationFields = byKey(nextRelation.fields ?? [], (field) => field.field);
      diffNamedItems(
        "resource relation field",
        previousRelationFields,
        nextRelationFields,
        (fieldPath, message) => breaking(`${path}.${relationPath}.${fieldPath}`, message),
        (fieldPath, message) => nonBreaking(`${path}.${relationPath}.${fieldPath}`, message),
        (fieldPath, previousField, nextField, relationBreaking, relationNonBreaking) => {
          compareResourceField(`${path}.${relationPath}.${fieldPath}`, previousField, nextField, relationBreaking, relationNonBreaking);
        }
      );
    }
  );
}

function compareResourceField(
  path: string,
  previous: FddpContractResourceField,
  next: FddpContractResourceField,
  addBreaking: (path: string, message: string) => void,
  addNonBreaking: (path: string, message: string) => void
): void {
  compareTypeAndNullability(path, previous, next, addBreaking, addNonBreaking);
  if (previous.filterable && !next.filterable) {
    addBreaking(path, "resource field is no longer filterable");
  } else if (!previous.filterable && next.filterable) {
    addNonBreaking(path, "resource field became filterable");
  }
  if (previous.orderable && !next.orderable) {
    addBreaking(path, "resource field is no longer orderable");
  } else if (!previous.orderable && next.orderable) {
    addNonBreaking(path, "resource field became orderable");
  }
}

function compareContractCommand(
  path: string,
  previous: FddpContractCommand,
  next: FddpContractCommand,
  options: FddpContractDiffOptions,
  addBreaking: (path: string, message: string) => void,
  addNonBreaking: (path: string, message: string) => void
): void {
  compareStringProperty(path, "permission", previous.permission, next.permission, addNonBreaking);
  compareStringProperty(path, "owner", previous.owner, next.owner, addNonBreaking);
  compareStringProperty(path, "auditLevel", previous.auditLevel, next.auditLevel, addNonBreaking);
  if (!previous.idempotencyRequired && next.idempotencyRequired) {
    addByPolicy(options.allowIdempotencyTighten, addBreaking, addNonBreaking, path, "command now requires idempotency key");
  } else if (previous.idempotencyRequired && !next.idempotencyRequired) {
    addNonBreaking(path, "command no longer requires idempotency key");
  }

  const previousInput = byKey(previous.input ?? [], (field) => field.field);
  const nextInput = byKey(next.input ?? [], (field) => field.field);
  diffNamedItems(
    "command input",
    previousInput,
    nextInput,
    (fieldPath, message) => addBreaking(`${path}.${fieldPath}`, message),
    (fieldPath, message) => addNonBreaking(`${path}.${fieldPath}`, message),
    (fieldPath, previousField, nextField, breaking, nonBreaking) => {
      compareCommandInput(`${path}.${fieldPath}`, previousField, nextField, options, breaking, nonBreaking);
    }
  );

  for (const [fieldPath, nextField] of nextInput) {
    if (!previousInput.has(fieldPath) && nextField.required) {
      addByPolicy(options.allowRequiredCommandInputAdd, addBreaking, addNonBreaking, `${path}.${fieldPath}`, "required command input added");
    }
  }
}

function compareCommandInput(
  path: string,
  previous: FddpContractInputField,
  next: FddpContractInputField,
  options: FddpContractDiffOptions,
  addBreaking: (path: string, message: string) => void,
  addNonBreaking: (path: string, message: string) => void
): void {
  compareTypeAndNullability(path, previous, next, addBreaking, addNonBreaking);
  if (!previous.required && next.required) {
    addByPolicy(options.allowCommandInputRequiredTighten, addBreaking, addNonBreaking, path, "command input became required");
  } else if (previous.required && !next.required) {
    addNonBreaking(path, "command input became optional");
  }
}

function addByPolicy(
  allowed: boolean | undefined,
  addBreaking: (path: string, message: string) => void,
  addNonBreaking: (path: string, message: string) => void,
  path: string,
  message: string
): void {
  if (allowed) {
    addNonBreaking(path, `${message} (allowed by diff policy)`);
    return;
  }
  addBreaking(path, message);
}

function compareTypeAndNullability(
  path: string,
  previous: { type: string; nullable?: boolean },
  next: { type: string; nullable?: boolean },
  addBreaking: (path: string, message: string) => void,
  addNonBreaking: (path: string, message: string) => void
): void {
  if (previous.type !== next.type) {
    addBreaking(path, `type changed from ${previous.type} to ${next.type}`);
  }
  if (previous.nullable && !next.nullable) {
    addBreaking(path, "field is no longer nullable");
  } else if (!previous.nullable && next.nullable) {
    addNonBreaking(path, "field became nullable");
  }
}

function compareDeprecated(
  path: string,
  previous: boolean | undefined,
  next: boolean | undefined,
  addNonBreaking: (path: string, message: string) => void
): void {
  if (!previous && next) {
    addNonBreaking(path, "marked deprecated");
  } else if (previous && !next) {
    addNonBreaking(path, "no longer marked deprecated");
  }
}

function compareStringProperty(
  path: string,
  property: string,
  previous: string | undefined,
  next: string | undefined,
  addNonBreaking: (path: string, message: string) => void
): void {
  if (previous !== next) {
    addNonBreaking(path, `${property} changed from ${String(previous)} to ${String(next)}`);
  }
}
